"""Measure and export the two pieces of art the square's landing plays.

Dev dependencies: Pillow, NumPy (as build_environment.py).
Run python3 tools/build_square_landing.py, then python3 tools/build_manifest.py.

  craft   assets/new4/square-craft.png, the square craft seen from the angle
  land    assets/new4/square-land.png, the square island seen from the angle

Both are only cropped to what is drawn and saved as webp: nothing is painted
or moved. What this works out is where each one's SQUARE is in its own
picture -- the corners of the visible faces, not the image's rectangle or
its transparent padding -- so js/square-landing.js can set the craft's
underside down on the island's top face corner for corner.

Each slab is measured off its silhouette. The two back edges of its top
face are the upper outline left and right of the back corner, and the two
front edges of its base are the lower outline either side of the front
corner; a straight line is fitted to the middle of each (the rounded
corners themselves are left out), and the corners are where those lines
meet, or where they reach the outline's far left and right. The walls are
upright, so the hidden corners -- the top face's front, the base's back --
are the seen ones moved by the wall's height. Writes
assets/images/square-landing/ and js/square-landing-assets.js.
"""
import json
from pathlib import Path

import numpy as np
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'assets/new4'
OUT = ROOT / 'assets/images/square-landing'
JS = ROOT / 'js/square-landing-assets.js'

ART = {'craft': 'square-craft.png', 'land': 'square-land.png'}
PAD = 4          # px kept round the drawing when it is cropped
TRIM = .12       # share of the width left out of each edge fit, at both ends


def line(xs, ys):
    k, c = np.polyfit(xs, ys, 1)
    return k, c


def meet(a, b):
    x = (b[1] - a[1]) / (a[0] - b[0])
    return x, a[0] * x + a[1]


def at(ln, x):
    return ln[0] * x + ln[1]


def measure(alpha):
    m = alpha > 128
    cols = np.nonzero(m.any(axis=0))[0]
    x0, x1 = cols.min(), cols.max()
    w = x1 - x0
    top = np.array([np.nonzero(m[:, x])[0].min() if m[:, x].any() else -1 for x in range(m.shape[1])])
    bot = np.array([np.nonzero(m[:, x])[0].max() if m[:, x].any() else -1 for x in range(m.shape[1])])
    xb = int(np.argmin(np.where(top >= 0, top, 1e9)))      # the back corner's column
    xf = int(np.argmax(bot))                               # the front corner's column

    def fit(prof, lo, hi):
        lo, hi = int(lo + TRIM * w), int(hi - TRIM * w)
        xs = np.arange(lo, hi)
        return line(xs, prof[lo:hi])

    bl, br = fit(top, x0, xb), fit(top, xb, x1)
    fl, fr = fit(bot, x0, xf), fit(bot, xf, x1)

    back = meet(bl, br)
    front = meet(fl, fr)
    lt, rt = (x0, at(bl, x0)), (x1, at(br, x1))
    lb, rb = (x0, at(fl, x0)), (x1, at(fr, x1))
    wall = ((lb[1] - lt[1]) + (rb[1] - rt[1])) / 2

    r = lambda p: [round(float(p[0]), 1), round(float(p[1]), 1)]
    return {
        'top': {'l': r(lt), 'b': r(back), 'r': r(rt), 'f': r((front[0], front[1] - wall))},
        'base': {'l': r(lb), 'b': r((back[0], back[1] + wall)), 'r': r(rb), 'f': r(front)},
        'wall': round(float(wall), 1),
    }


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    data = {}
    for key, name in ART.items():
        img = Image.open(SOURCE / name).convert('RGBA')
        a = np.array(img)
        ys, xs = np.nonzero(a[..., 3] > 8)
        box = (max(0, xs.min() - PAD), max(0, ys.min() - PAD),
               min(img.width, xs.max() + 1 + PAD), min(img.height, ys.max() + 1 + PAD))
        crop = img.crop(box)
        geo = measure(np.array(crop)[..., 3])
        dst = OUT / (key + '.webp')
        crop.save(dst, 'WEBP', quality=90, method=6)
        data[key] = dict(src=dst.relative_to(ROOT).as_posix(), source=(SOURCE / name).relative_to(ROOT).as_posix(),
                         size=[crop.width, crop.height], **geo)
        print(key, crop.size, geo)

    JS.write_text('// Generated by tools/build_square_landing.py\n'
                  'window.GeoSquareLandingAssets = ' + json.dumps(data, separators=(',', ':')) + ';\n')


if __name__ == '__main__':
    main()
