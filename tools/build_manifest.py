"""Write js/manifest.js: the byte size of every shipped asset.

The start gate (js/script.js + js/preload.js) weights its loading
bar by these figures, so the bar reflects real bytes before the
first Content-Length has come back. Run it again whenever a file
under assets/ is added, replaced or removed:

    python tools/build_manifest.py

Dev tooling only: this file is not needed at runtime and should be
left out of any deploy.
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ASSETS = os.path.join(ROOT, "assets")
OUT = os.path.join(ROOT, "js", "manifest.js")

# licence texts and the like are never fetched by the page
SKIP_EXT = {".txt", ".md"}


def main():
    sizes = {}
    for dirpath, _dirs, files in os.walk(ASSETS):
        for name in sorted(files):
            if os.path.splitext(name)[1].lower() in SKIP_EXT:
                continue
            if name.startswith(".") or name in ("Thumbs.db", "desktop.ini"):
                continue
            full = os.path.join(dirpath, name)
            rel = os.path.relpath(full, ROOT).replace(os.sep, "/")
            sizes[rel] = os.path.getsize(full)

    body = json.dumps(sizes, indent=2, sort_keys=True, ensure_ascii=True)
    text = (
        "/* GENERATED by tools/build_manifest.py from the files on disk — do\n"
        "   not edit by hand. Keys are paths relative to index.html, decoded\n"
        "   (a space is a space); values are bytes. The loading bar weights\n"
        "   each file by this before its Content-Length arrives. */\n"
        "window.GeoManifest = " + body + ";\n"
    )
    with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)

    total = sum(sizes.values())
    print(f"{len(sizes)} assets, {total:,} bytes -> {os.path.relpath(OUT, ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
