/* Every landing's environment: the square's, played on every round's site
   B (`reef` in js/pages.js). Gameplay remains in pages/pilot/script.
   Artwork metadata is generated by tools/build_environment.py (the sea,
   the rocks, the square's platform) and tools/build_lands.py (the other
   shapes' slabs). All positions are in the existing site B camera frame.
   Only strew() draws a new seed.

   The sea is the supplied layers only, bottom to top:

     01  the ocean, "bg water"   css/reef.css, on .s3-bg
     02  rocks under the water   "underwater rock layer 02", strewn in the
                                 open water
         dry land                the landing platforms -- the square's
                                 platform, or the round's shape as a slab
                                 of rock -- a few small rocks round each,
                                 and THE BIG ROCKS: two islands of rock
                                 along the frame's edges, hanging a little
                                 way off it, and a few clusters out on the
                                 open water (tools/build_rocks.py)

   The water itself, its shores round all this land and the breach as land
   comes up are drawn by js/reef-water.js, under all of it. */
(function (global) {
  'use strict';
  var doc = document, ART = global.GeoEnvironmentAssets;
  var states = new Map(), serial = 0, prepared;
  var missing = new Set();
  var CONFIG = {
    seed: 0x53ea2026, attempts: 64, satellites: [1, 3], submerged: 6,
    /* a big island of rock: its longer side as a share of the screen's
       shorter side, how far it hangs off the edge it lies along (a share of
       the frame on that axis -- past the follow of the piloted camera, so
       the land runs on when the world slides, and never past the margin
       the islets keep round site B), and how many places are tried */
    bigSize: [.26, .36], bigOverhang: [.03, .08], bigAttempts: 120,
    /* and the clusters on the open water: how many, and their size */
    clusters: [2, 4], clusterSize: [.08, .13],
    deepSize: [.11, .2],
    riseMs: 1400, risePx: 14, deepOpacity: .62
  };
  function random(seed) {
    return function () {
      seed |= 0; seed = seed + 0x6D2B79F5 | 0;
      var t = Math.imul(seed ^ seed >>> 15, 1 | seed);
      t = t + Math.imul(t ^ t >>> 7, 61 | t) ^ t;
      return ((t ^ t >>> 14) >>> 0) / 4294967296;
    };
  }
  function r(n) { return Math.round(n * 100) / 100; }
  function node(tag, cls, parent) {
    var el = doc.createElement(tag); el.className = cls;
    if (parent) parent.appendChild(el);
    return el;
  }
  function waterSeed(src, salt) {
    var seed = salt || 0;
    for (var i = 0; i < src.length; i++) seed = Math.imul(seed ^ src.charCodeAt(i), 16777619);
    return seed >>> 0;
  }
  function box(el, host) {
    var x = 0, y = 0, n = el;
    while (n && n !== host) { x += n.offsetLeft; y += n.offsetTop; n = n.offsetParent; }
    return { l: x, t: y, r: x + el.offsetWidth, b: y + el.offsetHeight };
  }
  function grow(b, p) { return { l: b.l - p, t: b.t - p, r: b.r + p, b: b.b + p }; }
  function hits(a, b) { return a.l < b.r && a.r > b.l && a.t < b.b && a.b > b.t; }
  function rect(x, y, w, h) { return { l: x, t: y, r: x + w, b: y + h }; }
  function chromeBoxes(round, screen) {
    var out = [];
    [round.el.stick, round.el.lives, doc.getElementById('nav')].forEach(function (el) {
      if (el && el.offsetWidth) out.push(grow(box(el, el.id === 'nav' ? screen.parentNode : screen), 12));
    });
    var bar = screen.querySelector('.topbar'), frame = bar && bar.querySelector('.topbar__frame');
    if (frame) {
      // The header is centred with translateX(-50%); its 200px wrapper
      // includes empty slide-out space. Reserve the visible capsule only.
      var b = box(bar, screen);
      out.push(grow(rect(b.l - bar.offsetWidth / 2, b.t, frame.offsetWidth, frame.offsetHeight), 12));
    }
    return out;
  }

  function image(meta, parent) {
    var img = node('img', 'env-image', parent);
    img.alt = ''; img.draggable = false; img.width = meta.size[0]; img.height = meta.size[1];
    img.addEventListener('error', function () {
      missing.add(meta.src); parent.classList.add('is-missing');
      console.warn('Environment artwork unavailable:', meta.src);
    }, { once: true });
    img.src = meta.src;
    return img;
  }
  // Spray thrown off land breaking the surface: droplets leave points
  // spread evenly along its waterline, rise towards the camera and fall
  // back further out. Sizes and reach are shares of the object's width;
  // css/reef.css plays them off `.pad.is-up`.
  function spray(meta, el, salt, big) {
    var rng = random(waterSeed(meta.src, (salt | 0) + 0x5eed));
    var line = meta.waterline, W = meta.size[0], H = meta.size[1], total = 0;
    var lengths = line.map(function (a, i) {
      var b = line[(i + 1) % line.length], len = Math.hypot(b[0] - a[0], b[1] - a[1]);
      total += len; return len;
    });
    var box = node('div', 'env-spray', el), count = big ? 22 : 7;
    for (var i = 0; i < count; i++) {
      var at = (i + rng() * .8) / count * total, k = 0;
      while (at > lengths[k] && k < lengths.length - 1) at -= lengths[k++];
      var a = line[k], b = line[(k + 1) % line.length], f = at / (lengths[k] || 1);
      var x = a[0] + (b[0] - a[0]) * f, y = a[1] + (b[1] - a[1]) * f;
      var dx = x - W / 2, dy = y - H / 2, len = Math.hypot(dx, dy) || 1;
      var size = big ? 2.6 + rng() * 2.6 : 9 + rng() * 6;
      var reach = big ? 9 + rng() * 22 : 30 + rng() * 45;
      var drop = node('i', 'env-drop', box);
      drop.style.left = r(x / W * 100) + '%'; drop.style.top = r(y / H * 100) + '%';
      drop.style.width = r(size) + '%';
      // translate percentages are of the droplet's own size
      drop.style.setProperty('--tx', r(dx / len * reach / size * 100) + '%');
      drop.style.setProperty('--ty', r(dy / len * reach / size * 100) + '%');
      drop.style.setProperty('--drop-delay', Math.round(rng() * 240) + 'ms');
      drop.style.setProperty('--drop-time', Math.round(620 + rng() * 480) + 'ms');
    }
  }
  // A dry object: its artwork, and for land that rises, the water it
  // comes up through: a blue wash that dries off, wet edges that drain
  // last, a wet shine, and the spray it throws.
  function dryObject(meta, cls, reveal, waveSeed) {
    var el = node('div', cls + ' env-object');
    el.setAttribute('aria-hidden', 'true');
    var art = node('div', 'env-art', el);
    image(meta, art);
    if (reveal) {
      ['env-wet', 'env-wet env-wet--edge', 'env-wet env-wet--sheen'].forEach(function (c) {
        var tint = node('span', c, art);
        tint.style.maskImage = 'url("' + meta.src + '")';
        tint.style.webkitMaskImage = 'url("' + meta.src + '")';
      });
      spray(meta, el, waveSeed, cls === 'env-platform');
    }
    return el;
  }

  function configure(screen) {
    var s = screen.style;
    [['--env-rise', CONFIG.riseMs + 'ms'], ['--env-lift', CONFIG.risePx + 'px'],
      ['--env-deep-alpha', CONFIG.deepOpacity]]
      .forEach(function (v) { s.setProperty(v[0], v[1]); });
  }
  // The platform an island of `shape` is stood in the sea as, and where
  // it goes in the pad's box (per cent): the square's is its platform
  // (the top face, rectified square, centred on the centre of area, so
  // the island the player lands on is exactly the one laid out); every
  // other shape's is its own slab tile, its painted box laid onto the
  // outline's box -- the same picture, on the same spot.
  function platformOf(shape) {
    var land = global.GeoPages.land[shape];
    if (!land) return null;
    if (shape === 'square') {
      var f = ART.platform.footprint;
      var side = Math.min(land.ext[2] - land.ext[0], land.ext[3] - land.ext[1]) * 100;
      var scale = side / f[2];
      return { meta: ART.platform, scale: scale,
        x: land.cx * 100 - side / 2 - f[0] * scale, y: land.cy * 100 - side / 2 - f[1] * scale };
    }
    var meta = ART.lands && ART.lands[shape];
    if (!meta) return null;
    var fp = meta.footprint, k = (land.ext[2] - land.ext[0]) * 100 / fp[2];
    return { meta: meta, scale: k, x: land.ext[0] * 100 - fp[0] * k, y: land.ext[1] * 100 - fp[1] * k };
  }
  function dress(screen) {
    if (states.has(screen) || !ART) return;
    var site = screen.querySelector('.site--b');
    if (!site) return;
    var root = node('div', 'env-world', site);
    site.insertBefore(root, site.firstChild);
    root.setAttribute('aria-hidden', 'true');
    var deep = node('div', 'env-deep', root);
    var bigs = node('div', 'env-bigs', root);
    var clusters = [];
    site.querySelectorAll('.pad[data-area]').forEach(function (pad) {
      var old = pad.querySelector('.pad__img');
      var at = platformOf(pad.dataset.shape);
      if (!old || !at) return;
      // No gameplay metadata, hit polygon, fit trace, label or size is edited.
      var art = dryObject(at.meta, 'env-platform', true, +pad.dataset.area);
      var x = at.x, y = at.y, scale = at.scale;
      art.style.left = r(x) + '%'; art.style.top = r(y) + '%';
      art.style.width = r(at.meta.size[0] * scale) + '%';
      old.replaceWith(art);
      var satellites = node('div', 'env-satellites', pad);
      clusters.push({ pad: pad, art: art, satellites: satellites, local: [],
        extent: { l: x / 100, t: y / 100, r: (x + at.meta.size[0] * scale) / 100,
          b: (y + at.meta.size[1] * scale) / 100 } });
    });
    var state = { screen: screen, site: site, root: root, deep: deep,
      bigs: bigs, clusters: clusters, seed: 0, landing: screen.hasAttribute('data-landing') };
    states.set(screen, state);
    // Resize may suppress a decoration which no longer fits, but never draws
    // a new position or seed. Restoring the size restores the same decoration.
    new ResizeObserver(function () { fitDecorations(state); }).observe(site);
    configure(screen);
  }
  function prepare() {
    if (prepared) return prepared;
    if (!ART) return Promise.resolve();
    var lands = Object.keys(ART.lands || {}).map(function (k) { return ART.lands[k]; });
    prepared = Promise.all([ART.platform, ART.ocean].concat(ART.dry, ART.big || [], ART.deep, lands).map(function (meta) {
      var img = new Image(); img.src = meta.src;
      return img.decode().catch(function () {
        missing.add(meta.src); console.warn('Environment artwork unavailable:', meta.src);
      });
    }));
    return prepared;
  }
  function init(stage) {
    (stage || doc).querySelectorAll('.screen[data-reef]').forEach(dress);
  }
  function vmin() { return Math.min(global.innerWidth, global.innerHeight) / 100; }
  function place(el, x, y, w, W, H) {
    el.style.left = r(x / W * 100) + '%'; el.style.top = r(y / H * 100) + '%';
    el.style.width = r(w / vmin()) + 'vmin';
  }
  // A big island lying along one edge of the frame, part of it off the
  // edge: pinned to that edge, so it stays there through any resize.
  function alongEdge(el, side, x, y, w, W, H) {
    var width = w / vmin();
    if (side === 'left' || side === 'right') el.style[side] = r((side === 'left' ? x : W - x - w) / W * 100) + '%';
    else el.style.left = r(x / W * 100) + '%';
    if (side === 'top' || side === 'bottom') el.style[side] = r((side === 'top' ? y : H - y - (w * el.ratio)) / H * 100) + '%';
    else el.style.top = r(y / H * 100) + '%';
    el.style.width = r(width) + 'vmin';
  }
  // Reserve a corridor from spawn to each approved target. The decoration
  // sampler never changes targets, hit areas or the ship's movement limits.
  function corridorHits(b, a, z, hull) {
    var lo = 0, hi = 1;
    var axes = [[a.x, z.x - a.x, b.l - hull.x, b.r + hull.x],
                [a.y, z.y - a.y, b.t - hull.y, b.b + hull.y]];
    for (var i = 0; i < axes.length; i++) {
      var v = axes[i];
      if (Math.abs(v[1]) < .001) { if (v[0] < v[2] || v[0] > v[3]) return false; }
      else {
        var t0 = (v[2] - v[0]) / v[1], t1 = (v[3] - v[0]) / v[1];
        lo = Math.max(lo, Math.min(t0, t1)); hi = Math.min(hi, Math.max(t0, t1));
        if (lo > hi) return false;
      }
    }
    return true;
  }
  function strew(round, seed) {
    var s = round && states.get(round.node);
    if (!s) return;
    var W = s.site.clientWidth, H = s.site.clientHeight, S = Math.min(W, H);
    if (!W || !H) return;
    s.seed = seed == null ? (CONFIG.seed + ++serial * 2654435761) >>> 0 : seed >>> 0;
    var rng = random(s.seed), between = function (lo, hi) { return lo + rng() * (hi - lo); };
    var occupied = [], hard = chromeBoxes(round, s.screen), targets = [], ship = round.sites.b.el.ship;
    // the survey's site B has no craft and no islands: only scenery is strewn
    var sw = ship ? ship.offsetWidth : 0;
    var sb = ship ? box(ship, s.site) : null;
    var spawn = sb ? { x: (sb.l + sb.r) / 2, y: (sb.t + sb.b) / 2 } : null;
    var radius = sw * .34 + 6;
    var corridorHull = { x: sw * .32 + 4, y: sw * .30 + 4 };
    if (sb) hard.push({ l: sb.l - sw * .32, t: sb.t - 12, r: sb.r + 12, b: sb.b + sw * .28 });
    s.clusters.forEach(function (c) {
      var b = box(c.pad, s.site), w = c.pad.offsetWidth, e = c.extent;
      var land = global.GeoPages.land[c.pad.dataset.shape] || { cx: .5, cy: .5 };
      c.box = rect(b.l + e.l * w, b.t + e.t * w, (e.r - e.l) * w, (e.b - e.t) * w);
      occupied.push(grow(c.box, 10));
      targets.push({ x: b.l + w * land.cx, y: b.t + w * land.cy });
      c.satellites.replaceChildren(); c.local = [];
    });
    function safe(b, corridors) {
      return !hard.concat(occupied).some(function (o) { return hits(b, o); }) &&
        (!corridors || !spawn || !targets.some(function (t) { return corridorHits(b, spawn, t, corridorHull); }));
    }
    // THE BIG ROCKS, first after the platforms. The two islands each at
    // most once, in a fresh order, each lying along one edge of the frame
    // -- left, right, top or bottom -- and hanging a little way off it, so
    // the land runs on past the frame when the piloted camera slides the
    // world (js/pilot.js). On a full round site B's left edge is site A's
    // right, and the lens on site A looks down site B's upper half there,
    // so on that edge an island either sits wholly inside the frame or
    // lies in the lower half. The small rocks then find room round them.
    s.bigs.replaceChildren();
    var all = (ART.big || []), shuffle = function (list) {
      for (var o = list.length - 1; o > 0; o--) {
        var swap = Math.floor(rng() * (o + 1)), keep = list[o]; list[o] = list[swap]; list[swap] = keep;
      }
      return list;
    };
    var sides = shuffle(['left', 'right', 'top', 'bottom']);
    shuffle(all.filter(function (m) { return m.large; })).forEach(function (bm, index) {
      // its own edge first, then the others, so two islands never share one
      // unless nowhere else has room
      for (var a = 0; a < CONFIG.bigAttempts * sides.length; a++) {
        var side = sides[(index + Math.floor(a / CONFIG.bigAttempts)) % sides.length];
        var long = S * between(CONFIG.bigSize[0], CONFIG.bigSize[1]);
        var bw = bm.size[0] >= bm.size[1] ? long : long * bm.size[0] / bm.size[1], bh = bw * bm.size[1] / bm.size[0];
        var over = between(CONFIG.bigOverhang[0], CONFIG.bigOverhang[1]);
        var bx, by;
        if (side === 'left' || side === 'right') {
          by = between(H * .1, H - bh - H * .06);
          var inside = !s.landing && side === 'left' && by < H * .55;
          var off = inside ? -between(.01, .03) * W : over * W;
          bx = side === 'left' ? -off : W - bw + off;
        } else {
          bx = between(W * .04, W - bw - W * .04);
          by = side === 'top' ? -over * H : H - bh + over * H;
        }
        // what is on the frame is what has to be clear
        var bb = grow(rect(Math.max(bx, 0), Math.max(by, 0), Math.min(bx + bw, W) - Math.max(bx, 0),
                           Math.min(by + bh, H) - Math.max(by, 0)), 8);
        if (bb.r - bb.l < bw * .4 || bb.b - bb.t < bh * .4 || !safe(bb, true)) continue;
        var isle = dryObject(bm, 'env-big', false, s.seed + index);
        isle.ratio = bm.size[1] / bm.size[0];
        alongEdge(isle, side, bx, by, bw, W, H); s.bigs.appendChild(isle); occupied.push(bb); break;
      }
    });
    // and a few clusters of rock out on the open water
    var small = shuffle(all.filter(function (m) { return !m.large; }));
    var want = CONFIG.clusters[0] + Math.floor(rng() * (CONFIG.clusters[1] - CONFIG.clusters[0] + 1));
    for (var ci = 0; ci < want && small.length; ci++) {
      var cm = small[ci % small.length];
      for (var ct = 0; ct < CONFIG.attempts; ct++) {
        var cw = S * between(CONFIG.clusterSize[0], CONFIG.clusterSize[1]), chh = cw * cm.size[1] / cm.size[0];
        var cx = between(W * .02, W - cw - W * .02), cy = between(H * .14, H - chh - 32);
        var cb = grow(rect(cx, cy, cw, chh), 10);
        if (!safe(cb, true)) continue;
        var cluster = dryObject(cm, 'env-big env-big--cluster', false, s.seed + 7 * ci);
        place(cluster, cx, cy, cw, W, H); s.bigs.appendChild(cluster); occupied.push(cb); break;
      }
    }
    s.clusters.forEach(function (c) {
      var base = box(c.pad, s.site), pw = c.pad.offsetWidth;
      var n = CONFIG.satellites[0] + Math.floor(rng() * (CONFIG.satellites[1] - CONFIG.satellites[0] + 1));
      for (var j = 0; j < n; j++) {
        var meta = ART.dry[Math.floor(rng() * ART.dry.length)];
        // If the random draw cannot place even one companion, try a small
        // rock at 96 fixed side stations, extending out past a neighbouring
        // approach corridor if necessary. Additional rocks remain optional.
        for (var k = 0; k < CONFIG.attempts + (c.local.length ? 0 : 96); k++) {
          var fallback = k >= CONFIG.attempts, station = k - CONFIG.attempts;
          var w = pw * (fallback ? .14 : between(.16, .25)), h = w * meta.size[1] / meta.size[0];
          var side = fallback ? station % 4 : Math.floor(rng() * 4);
          var along = fallback ? [.3, .5, .7][Math.floor(station / 4) % 3] : between(.25, .75);
          var gap = fallback ? 20 + Math.floor(station / 12) * 16 : between(14, Math.max(23, radius - (c.box.r - c.box.l) * .5 + 30));
          var x = side === 0 ? c.box.l - w - gap : side === 1 ? c.box.r + gap : c.box.l + (c.box.r - c.box.l) * along - w / 2;
          var y = side === 2 ? c.box.t - h - gap : side === 3 ? c.box.b + gap : c.box.t + (c.box.b - c.box.t) * along - h / 2;
          var b = grow(rect(x, y, w, h), 5);
          if (b.l < 8 || b.t < H * .14 || b.r > W - 8 || b.b > H - 32 || !safe(b, true)) continue;
          var rock = dryObject(meta, 'env-satellite', true, s.seed + +c.pad.dataset.area * 31 + j);
          var local = { x: (x - base.l) / pw * 100, y: (y - base.t) / pw * 100, w: w / pw * 100, src: meta.src };
          rock.style.left = r(local.x) + '%'; rock.style.top = r(local.y) + '%'; rock.style.width = r(local.w) + '%';
          rock.style.setProperty('--satellite-delay', Math.round(between(80, 160)) + 'ms');
          c.satellites.appendChild(rock); c.local.push(local); occupied.push(b); break;
        }
      }
    });
    s.deep.replaceChildren();
    for (var i = 0; i < CONFIG.submerged; i++) {
      var dm = ART.deep[i % ART.deep.length];
      for (var t = 0; t < CONFIG.attempts; t++) {
        var dw = S * between(CONFIG.deepSize[0], CONFIG.deepSize[1]), dh = dw * dm.size[1] / dm.size[0];
        var dx = between(-dw * .1, W - dw * .9), dy = between(H * .12, H - dh);
        var db = grow(rect(dx, dy, dw, dh), 8);
        if (!safe(db, true)) continue;
        var deep = node('div', 'env-submerged', s.deep);
        // js/reef-water.js redraws it through the water by this sprite
        deep.dataset.art = dm.src;
        image(dm, deep); place(deep, dx, dy, dw, W, H);
        occupied.push(db); break;
      }
    }
    s.round = round;
  }
  function fitDecorations(s) {
    if (!s.round) return;
    var hard = chromeBoxes(s.round, s.screen), occupied = [], W = s.site.clientWidth, H = s.site.clientHeight;
    s.clusters.forEach(function (c) { occupied.push(grow(box(c.art, s.site), 7)); });
    // Reset visibility for measurement only; the final result paints once.
    var decorations = ['.env-satellite', '.env-big', '.env-submerged'].reduce(function (all, selector) {
      return all.concat(Array.from(s.site.querySelectorAll(selector)));
    }, []);
    decorations.forEach(function (el) { el.hidden = false; });
    decorations.forEach(function (el) {
      var b = grow(box(el, s.site), 4);
      var outside = b.r < 0 || b.l > W || b.b < 0 || b.t > H;
      el.hidden = outside || hard.concat(occupied).some(function (other) { return hits(b, other); });
      if (!el.hidden) occupied.push(b);
    });
  }
  function pause() { states.forEach(function (s) { s.screen.classList.add('env-paused'); }); }
  function resume() { states.forEach(function (s) { s.screen.classList.remove('env-paused'); }); }
  if (global.GeoLife) { global.GeoLife.on('suspend', pause); global.GeoLife.on('resume', resume); }
  global.GeoReef = { init: init, prepare: prepare, strew: strew, config: CONFIG,
    inspect: function (screen) {
      var s = states.get(screen); if (!s) return null;
      return { seed: s.seed, clusters: s.clusters.map(function (c) {
        return { area: c.pad.dataset.area, satellites: c.local, extent: c.extent };
      }), missing: Array.from(missing) };
    }
  };
})(window);
